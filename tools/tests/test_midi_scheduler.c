/* Compile the real hardware MIDI parser with a deterministic clock and a
 * mocked voice engine. OF_PC would test only the SDK's no-op implementation.
 * Suppress just the RISC-V timer/service accessors and memory attributes. */
#include <assert.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

#define OF_TIMER_H
#define OF_SERVICES_H
#define OF_FASTRAM_H
#define OF_FASTDATA
static uint32_t clock_us;
static uint32_t of_time_us(void) { return clock_us; }
static void (*timer_callback)(void);
static void of_timer_set_callback(void (*cb)(void), uint32_t hz) {
    (void)hz;
    timer_callback = cb;
}
static const struct { uint32_t (*timer_get_us)(void); } test_svc = {of_time_us};
#define OF_SVC (&test_svc)
#include MIDI_SOURCE

