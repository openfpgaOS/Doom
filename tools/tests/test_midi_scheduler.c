static unsigned event_cost, tick_cost, ticks, all_offs;
static unsigned notes[16];
static uint32_t note_time[16];
int of_smp_bank_bind_preloaded(void) { return 0; }
const ofsf_header_t *of_smp_bank_get(void) { return &bank; }
const void *of_smp_bank_sample_base(void) { return &bank; }
int of_smp_zone_lookup(int b, int p, int k, int v,
                      const ofsf_zone_t **z, int n) {
    (void)b; (void)p; (void)k; (void)v; (void)z; (void)n;
    return 0;
}
void smp_voice_init(void) {}
int smp_voice_note_on(const ofsf_zone_t *z, int c, int n, int v, const void *b) {
    (void)z; (void)c; (void)n; (void)v; (void)b;
    return 0;
}
void smp_voice_note_off(int c, int n) {
    (void)n;
    notes[c]++;
    note_time[c] = clock_us;
}
void smp_voice_tick(void) {
    ticks++;
    clock_us += tick_cost;
    tick_cost = 0;
}
void smp_voice_tick_record_pump(uint32_t e, int t, int b) {
    (void)e; (void)t; (void)b;
}
void smp_voice_update_pan(int c, int p) {
    (void)c; (void)p;
    clock_us += event_cost;
    event_cost = 0;
}
